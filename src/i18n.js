function resolveLang(setting) {
  if (setting === 'ar' || setting === 'en') return setting;
  try {
    const nav = (typeof navigator !== 'undefined' && (navigator.language || (navigator.languages && navigator.languages[0]))) || '';
    if (/^ar\b/i.test(nav)) return 'ar';
    if (/^en\b/i.test(nav)) return 'en';
    const w = (typeof window !== 'undefined' && window.localStorage && window.localStorage.getItem('language')) || '';
    if (/^ar/i.test(w)) return 'ar';
  } catch (e) { /* fall through */ }
  return 'en';
}

function makeT(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  return (key, vars) => {
    let s = dict[key] != null ? dict[key] : (STRINGS.en[key] != null ? STRINGS.en[key] : key);
    if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
    return s;
  };
}

module.exports = { STRINGS, makeT, resolveLang };
