'use strict';
// Dependency-free bundler: concatenates src/*.js (CommonJS) into one main.js. `obsidian` stays external.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const srcDir = path.join(root, 'src');
const names = fs.readdirSync(srcDir).filter((f) => f.endsWith('.js')).map((f) => f.slice(0, -3));
const version = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8')).version;
let out = `/* Tdrive Sync ${version} — generated by scripts/build.js. Source: src/ */\n'use strict';\nvar __nodeRequire = require;\nvar __defs = {};\nvar __cache = {};\nfunction __load(n) {\n  if (__cache[n]) return __cache[n].exports;\n  var m = (__cache[n] = { exports: {} });\n  __defs[n](m, m.exports, function (r) { return r.indexOf('./') === 0 ? __load(r.slice(2)) : __nodeRequire(r); });\n  return m.exports;\n}\n`;
for (const n of names) {
  const code = fs.readFileSync(path.join(srcDir, n + '.js'), 'utf8').replace(/^'use strict';\n/, '');
  out += `__defs[${JSON.stringify(n)}] = function (module, exports, require) {\n${code}\n};\n`;
}
out += `module.exports = __load('plugin');\n`;
fs.writeFileSync(path.join(root, 'main.js'), out);
console.log('built main.js', Buffer.byteLength(out), 'bytes,', names.length, 'modules');
